-- Run once in the SAP HANA schema that contains CANDIDATE_PROFILE.
-- One current match snapshot per candidate and job; this is separate from applications.
CREATE COLUMN TABLE CANDIDATE_JOB_MATCH (
    CANDIDATE_ID NVARCHAR(36) NOT NULL,
    JOB_ID INTEGER NOT NULL,
    SKILLS_JSON BLOB NOT NULL,
    MATCH_JSON BLOB NOT NULL,
    ANALYZED_DOCUMENT_ID NVARCHAR(36),
    UPDATED_AT TIMESTAMP NOT NULL,
    PRIMARY KEY (CANDIDATE_ID, JOB_ID),
    FOREIGN KEY (CANDIDATE_ID) REFERENCES CANDIDATE_PROFILE (CANDIDATE_ID)
);
