-- Run once in the SAP HANA schema containing CANDIDATE_PROFILE.
CREATE COLUMN TABLE CANDIDATE_DOCUMENT (
    DOCUMENT_ID NVARCHAR(36) PRIMARY KEY,
    CANDIDATE_ID NVARCHAR(36) NOT NULL,
    DOCUMENT_KIND NVARCHAR(30) NOT NULL,
    FILE_NAME NVARCHAR(255) NOT NULL,
    CONTENT_TYPE NVARCHAR(255) NOT NULL,
    FILE_SIZE INTEGER NOT NULL,
    FILE_DATA BLOB NOT NULL,
    UPLOADED_AT TIMESTAMP NOT NULL
);

CREATE INDEX CANDIDATE_DOCUMENT_CANDIDATE_IDX
    ON CANDIDATE_DOCUMENT (CANDIDATE_ID);
