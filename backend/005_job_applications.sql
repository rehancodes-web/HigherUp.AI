-- Run once in the SAP HANA schema containing CANDIDATE_PROFILE and CANDIDATE_DOCUMENT.
-- A submitted application shares the candidate's already stored resume with the named employer.
CREATE COLUMN TABLE JOB_APPLICATION (
    APPLICATION_ID NVARCHAR(36) PRIMARY KEY,
    CANDIDATE_ID NVARCHAR(36) NOT NULL,
    CANDIDATE_EMAIL NVARCHAR(255) NOT NULL,
    COMPANY_NAME NVARCHAR(120) NOT NULL,
    JOB_ID INTEGER NOT NULL,
    ROLE_TITLE NVARCHAR(120) NOT NULL,
    RESUME_DOCUMENT_ID NVARCHAR(36) NOT NULL,
    PROFILE_JSON BLOB NOT NULL,
    STATUS NVARCHAR(30) NOT NULL,
    SUBMITTED_AT TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX JOB_APPLICATION_CANDIDATE_JOB_UQ
    ON JOB_APPLICATION (CANDIDATE_ID, COMPANY_NAME, JOB_ID);

CREATE INDEX JOB_APPLICATION_COMPANY_IDX
    ON JOB_APPLICATION (COMPANY_NAME, STATUS, SUBMITTED_AT);
