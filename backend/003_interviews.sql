-- Run once in the SAP HANA schema containing CANDIDATE_PROFILE.
-- Interview scheduling: recruiters publish slots, selected candidates get an invite
-- from the HigherUp.AI assistant and book one open slot. Used by interviews.py.

CREATE COLUMN TABLE INTERVIEW_SLOT (
    SLOT_ID NVARCHAR(36) PRIMARY KEY,
    RECRUITER_EMAIL NVARCHAR(255) NOT NULL,
    SLOT_DATE NVARCHAR(10) NOT NULL,        -- YYYY-MM-DD
    SLOT_TIME NVARCHAR(5) NOT NULL,         -- HH:MM (24h)
    LENGTH_MIN INTEGER NOT NULL,
    MODE NVARCHAR(30) NOT NULL,             -- Video call / On-site / Phone call
    INTERVIEWER NVARCHAR(120),
    BOOKED_INVITE_ID NVARCHAR(36),          -- NULL while the slot is open
    CREATED_AT TIMESTAMP NOT NULL
);
CREATE INDEX INTERVIEW_SLOT_RECRUITER_IDX ON INTERVIEW_SLOT (RECRUITER_EMAIL);

CREATE COLUMN TABLE INTERVIEW_INVITE (
    INVITE_ID NVARCHAR(36) PRIMARY KEY,
    RECRUITER_EMAIL NVARCHAR(255) NOT NULL,
    CANDIDATE_NAME NVARCHAR(120) NOT NULL,
    CANDIDATE_EMAIL NVARCHAR(255),          -- login email of the candidate this invite is for; only they can see it
    HEADLINE NVARCHAR(200),
    COMPANY NVARCHAR(120) NOT NULL,
    ROLE_TITLE NVARCHAR(120) NOT NULL,
    SLOT_ID NVARCHAR(36),                   -- set once the candidate books
    IS_READ BOOLEAN NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL
);
CREATE INDEX INTERVIEW_INVITE_RECRUITER_IDX ON INTERVIEW_INVITE (RECRUITER_EMAIL);
CREATE INDEX INTERVIEW_INVITE_CANDIDATE_IDX ON INTERVIEW_INVITE (CANDIDATE_EMAIL);

CREATE COLUMN TABLE INTERVIEW_MESSAGE (
    MESSAGE_ID NVARCHAR(36) PRIMARY KEY,
    INVITE_ID NVARCHAR(36) NOT NULL,
    SEQ_NO INTEGER NOT NULL,                -- order of messages within one invite
    SENDER NVARCHAR(10) NOT NULL,           -- 'ai' or 'you' (the candidate)
    BODY NVARCHAR(1000) NOT NULL,
    SHOW_SLOTS BOOLEAN NOT NULL,            -- true on the message that carries the slot picker
    CREATED_AT TIMESTAMP NOT NULL
);
CREATE INDEX INTERVIEW_MESSAGE_INVITE_IDX ON INTERVIEW_MESSAGE (INVITE_ID);
